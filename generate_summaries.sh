#!/bin/bash

echo 'This script will rewrite summaries/ and latex_tables/. Continue? (y/n)'
while true; do
    read answer
    case "$answer" in
	[yY]) break;;
	[nN]) exit;;
	*) echo 'Please answer "y" or "n"'
    esac
done

rm -rf summaries
mkdir summaries

rm -rf latex_tables
mkdir latex_tables

set -euo pipefail

### FIN-bench

# FIN-bench TSV summaries
mkdir summaries/finbench
for f in output/{poro-34b,TurkuNLP}/*/finbench.json; do
    d=$(dirname "$f")
    m=${d#output/}
    m=${m//\//_}
    o=summaries/finbench/${m}.tsv
    python3 finbench_summary.py "$f" > "$o"
done

# FIN-bench detailed Poro results table
o=latex_tables/poro-finbench-progression.tex

cat > "$o" <<EOF
% NOTE: this latex table is generated by the script
% https://github.com/LumiOpen/evals/blob/master/generate_summaries.sh.
% To change the table, you should probably edit and rerun the script.
\\begin{table}[t!]
\\centering
\\begin{tabular}{l|lll}
Step & Tokens & Trained & Average \\\\ \\hline
EOF

ls summaries/finbench/poro-34b_step*.tsv \
    | perl -pe 's/.*_step(\d+)\.tsv/$1/' | sort -n \
    | while read step; do
    f=summaries/finbench/poro-34b_step${step}.tsv
    tokens=$((step*2048*2048))
    tokens=$(python3 -c 'print(round('$tokens'/1e9))')"B"
    trained=$(python3 -c 'print(f"{'$step'/238418:.1%}")')
    avg=$(cat $f | egrep '^TOTAL' | perl -pe 's/^TOTAL\s+//')
    avg=$(python3 -c 'print(f"{'$avg':.1%}")')
    trained=${trained/\%/\\%}
    avg=${avg/\%/\\%}
    echo $step '&' $tokens '&' $trained '&' $avg '\\' >> "$o"
done

cat >> "$o" <<EOF
\\end{tabular}
\\caption{Poro progression on FIN-bench}
\\label{tab:poro-finbench-progression}
\\end{table}
EOF
